class ChessThemeDef {
  final String id;
  final String name;
  // Surfaces — layered depths
  final Color bg;
  final Color surface;
  final Color surfaceRaised;
  final Color line;
  // Text
  final Color ivory;
  final Color ivoryDim;
  // Metal accent (brass / copper / silver / gold)
  final Color accent;
  final Color accentLight;
  final Color accentDark;
  final Color onAccent;
  // Felt lining (captured trays)
  final Color felt;
  // Board squares: light pair + dark pair (subtle gradients)
  final Color sqLight;
  final Color sqLightHi;
  final Color sqDark;
  final Color sqDarkHi;
  // Walnut frame gradient
  final Color frameTop;
  final Color frameMid;
  final Color frameBot;
  // Piece woods
  final Color pieceWhite;
  final Color pieceWhiteHi;
  final Color pieceBlack;
  final Color pieceBlackHi;
  // Semantic
  final Color checkRed;
  final Color lastMove;
  final Color selGold;

  const ChessThemeDef({
    required this.id,
    required this.name,
    required this.bg,
    required this.surface,
    required this.surfaceRaised,
    required this.line,
    required this.ivory,
    required this.ivoryDim,
    required this.accent,
    required this.accentLight,
    required this.accentDark,
    required this.onAccent,
    required this.felt,
    required this.sqLight,
    required this.sqLightHi,
    required this.sqDark,
    required this.sqDarkHi,
    required this.frameTop,
    required this.frameMid,
    required this.frameBot,
    required this.pieceWhite,
    required this.pieceWhiteHi,
    required this.pieceBlack,
    required this.pieceBlackHi,
    required this.checkRed,
    required this.lastMove,
    required this.selGold,
  });
}

